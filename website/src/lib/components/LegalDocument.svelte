<!--
  One English legal document — Privacy Policy or Terms of Service.
  Shared by /privacy and /terms because the two pages differ only in
  which document they name.

  The body HTML comes from $lib/legal/documents.ts, generated by
  tools/legal/render.mjs from legal/*.md. The heading and version line
  come from the message catalogue, so no user-visible string is
  hard-coded in the generator.
-->

<script lang="ts">
  import { reveal } from "$lib/motion";
  import { fmt, messages, splitAt } from "$lib/i18n";
  import {
    LEGAL_DOCUMENTS,
    type LegalDocKey,
  } from "$lib/legal/documents";

  let { doc }: { doc: LegalDocKey } = $props();

  const m = messages.legal;

  // The site is English-only, so both the page chrome and the generated
  // body are British English.
  const rendering = $derived(LEGAL_DOCUMENTS[doc]["en-GB"]);

  const heading = $derived(
    doc === "privacy" ? m.privacyHeading : m.termsHeading,
  );

  // Split rather than interpolated: `{date}` stands in for a <time>
  // element, and the catalogue carries no HTML.
  const versionParts = $derived(
    splitAt(fmt(m.versionLine, { version: rendering.version }), "date"),
  );
</script>

<article
  class="site-container prose py-16 reveal"
  lang={rendering.locale}
  use:reveal
>
  <h1>{heading}</h1>

  <p>
    <strong>
      {#if rendering.effectiveDate !== null && rendering.effectiveDateISO !== null}
        {versionParts[0]}<time datetime={rendering.effectiveDateISO}
          >{rendering.effectiveDate}</time
        >{versionParts[1]}
      {:else}
        {fmt(m.versionLineUndated, { version: rendering.version })}
      {/if}
    </strong>
  </p>

  {@html rendering.html}
</article>
